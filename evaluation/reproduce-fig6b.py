"""
Reproduction script for Figure 6c in the paper.

Please note that the input data for this script is only a small subset (100 requests) of the original data (2000 requests) used 
in the paper. This is for the purpose of demonstration and quick verification of the results. As a result, the latency would be
lower than the original figure due to less average queuing latency. 

The original data can be generated by modifying the parameters in the script.
"""

import asyncio
import json
import os
import csv

from server import start_server, stop_server
from benchmark import run_test, prepare_real_test
from illustrator import draw_one_rl_diagram

NUM_THRESHOLD = 2000

cur_dir = os.path.dirname(os.path.realpath(__file__))
data_dir = f"{cur_dir}/data"
res_dir = f"{cur_dir}/results"

def read_csv(
    file_path: str,
    num_threshold: int,
) -> list:
    res = []
    with open(file_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for i, row in enumerate(reader):
            if i >= num_threshold:
                break
            res.append(row)
    return res

def prepare_ac_test(
    dataset_name: str,
    config: dict,
    server_name: str,
    num_threshold: int,
):
    """
    准备 Azure trace 数据。

    `num_threshold` 现在由外部传入，而不是写死在函数内部，
    这样可以先用小样本验证调度逻辑是否稳定，再扩大到更高负载。
    """
    ac_codepath = f"{data_dir}/AzureLLMInferenceTrace_code.csv"
    ac_convpath = f"{data_dir}/AzureLLMInferenceTrace_conv.csv"

    code_datas = read_csv(ac_codepath, num_threshold)
    conv_datas = read_csv(ac_convpath, num_threshold)

    prompts = [[10] * int(data["ContextTokens"]) for data in code_datas]
    output_lens = [int(data["GeneratedTokens"]) for data in code_datas]
    prompts += [[10] * int(data["ContextTokens"]) for data in conv_datas]
    output_lens += [int(data["GeneratedTokens"]) for data in conv_datas]

    res_file = f"{res_dir}/{server_name}-{dataset_name}"
    return prompts, output_lens, res_file, config["model_path"]


# Tweak hyperparameters here:

# vllm_rates = [0.2, 0.4, 0.5, 0.6]
# vllm_rates = [0.5, 1.5, 2.5, 3.1, 3.5, 3.7, 3.9]
# ours_rates = [0.5, 1.5, 2.5, 3.1, 3.5, 3.7, 3.9]
vllm_rates = [1.5, 2.5, 3.1, 3.5]
ours_rates = [1.5, 2.5, 3.1, 3.5]
# Rates of requests per second, reduce the number of elements in the list to speed up the evaluation process.


cur_dir = os.path.dirname(os.path.realpath(__file__))
with open(f"{cur_dir}/configs/config-4090-8b.json", "r") as f:
    config = json.load(f)


async def one_round(server_name: str):
    start_server(server_name, config)
    try:
        # Change the rate argument (in reqs/s) to other values to see more results
        # Feel free to comment out some of the following lines to reduce running time
        if server_name == "ours":
            for rate in ours_rates:
                await run_test(*prepare_ac_test("ac", config, server_name, NUM_THRESHOLD), rate=rate)
        if server_name == "vllm":
            for rate in vllm_rates:
                await run_test(*prepare_ac_test("ac", config, server_name, NUM_THRESHOLD), rate=rate)
    finally:
        stop_server()
    await asyncio.sleep(5)


async def main():
    await one_round("vllm")
    await one_round("ours")


if __name__ == "__main__":
    asyncio.run(main())
    draw_one_rl_diagram(
        title="fig6b",
        data_name="ac",
        sys_file_names=["vllm", "ours"],
        sys_legend_names=["VLLM", "Ours"],
        rate_lists=[vllm_rates, ours_rates],
        ylim=2,
        markers=["o", "x"],
        set_ylabel=True
    )